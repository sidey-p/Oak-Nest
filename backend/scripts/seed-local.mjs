// Seeds the database using the backend's own .env credentials.
// The DB password never leaves backend/.env — safe for shared projects.
// Usage: npm run seed   (after setting DB_PASSWORD in backend/.env)
import 'dotenv/config';
import pg from 'pg';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const dbDir = path.join(__dirname, '..', '..', 'database');

if (!process.env.DB_PASSWORD || process.env.DB_PASSWORD === 'PLACEHOLDER_NOT_SET') {
  console.error('ERROR: DB_PASSWORD is not set in backend/.env');
  console.error('Open backend/.env and set DB_PASSWORD to your Supabase database password.');
  process.exit(1);
}

const isPooler = String(process.env.DB_HOST || '').includes('pooler.supabase.com');

const pool = new pg.Pool({
  host: process.env.DB_HOST,
  port: Number(process.env.DB_PORT || 5432),
  user: process.env.DB_USER,
  password: process.env.DB_PASSWORD,
  database: process.env.DB_NAME,
  ssl: process.env.DB_SSL === 'true' ? { rejectUnauthorized: false } : undefined,
  connectionTimeoutMillis: 15000,
});

const run = async () => {
  let client;
  try {
    client = await pool.connect();

    // Step 1 — ensure identity columns allow seed inserts (converts GENERATED
    // ALWAYS -> GENERATED BY DEFAULT; no-op if already correct)
    console.log('Step 1/2: preparing identity columns...');
    const fixSql = fs.readFileSync(path.join(dbDir, 'fix-identity.sql'), 'utf8');
    await client.query(fixSql);

    // Step 2 — run the full seed (truncates + inserts sample data)
    // Uses a dedicated connection with prepared statements disabled so it
    // works through the Supabase transaction pooler (port 6543).
    console.log('Step 2/2: seeding sample data...');
    const seedSql = fs.readFileSync(path.join(dbDir, 'seed.sql'), 'utf8');
    const statements = seedSql
      .split(/;\s*\r?\n/)
      .map((s) => s.replace(/--.*$/gm, '').trim())
      .filter((s) => s.length > 0 && !s.startsWith('SELECT setval'));
    for (const stmt of statements) {
      await client.query(stmt);
    }
    const setvalStmts = seedSql
      .split(/;\s*\r?\n/)
      .map((s) => s.trim())
      .filter((s) => s.startsWith('SELECT setval'));
    for (const stmt of setvalStmts) {
      await client.query(stmt);
    }

    const counts = {};
    for (const t of ['users', 'categories', 'products', 'product_images', 'addresses', 'orders', 'order_items', 'payments', 'shipments', 'reviews', 'coupons', 'feedback', 'custom_design_requests', 'wishlist']) {
      const r = await client.query(`SELECT COUNT(*)::int AS n FROM ${t}`);
      counts[t] = r.rows[0].n;
    }

    console.log('\n=== SEED COMPLETE ===');
    console.table(counts);
    console.log('\nDemo accounts:');
    console.log('  Admin    — admin@furnishing.local / admin123');
    console.log('  Customer — customer@furnishing.local / customer123');
  } catch (err) {
    if (String(err.message).includes('password authentication failed')) {
      console.error('ERROR: Password authentication failed — check DB_PASSWORD in backend/.env');
    } else if (String(err.code) === 'ENOTFOUND' || String(err.message).includes('timeout')) {
      console.error('ERROR: Could not reach the database — check DB_HOST / internet connection.');
    } else {
      console.error('SEED FAILED:', err.message);
    }
    process.exitCode = 1;
  } finally {
    if (client) client.release();
    await pool.end();
  }
};

run();
